function getSubjectDisplayName(state: PromptFormState): string {
  if (state.subject === 'other') {
    return state.customSubject.trim() || 'Навчальний предмет';
  }
  return SUBJECTS.find((s) => s.id === state.subject)?.label ?? 'Навчальний предмет';
}

